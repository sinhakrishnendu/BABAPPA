cp branch_site_calibration_explicit_branch_truth_100k_mps_extreme_streamed/branch_site_calibration.json package/calibration/extreme_branch_site_calibration.json
cp branch_site_calibration_explicit_branch_truth_100k_mps_extreme_streamed/branch_site_calibrated_metrics.json package/calibration/extreme_branch_site_calibrated_metrics.json
cp deployable_model_manifest_template.json package/deployable_model_manifest.json
cp model_card_template.md package/model_card.md
echo 'Package staged under package/'
