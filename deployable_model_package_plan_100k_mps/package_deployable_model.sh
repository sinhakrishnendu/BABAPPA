#!/usr/bin/env bash
set -euo pipefail
echo 'USER-RUN ONLY - packages retained model artifacts; does not train.'
if python - <<'PY'
import json
from pathlib import Path
m=json.loads(Path('deployable_model_manifest_template.json').read_text())
raise SystemExit(1 if m.get('blocked') else 0)
PY
then
  mkdir -p package/models package/calibration package/reports
else
  echo 'Package plan is blocked; inspect deployable_model_manifest_template.json.'
  exit 1
fi
cp branch_site_neural_explicit_branch_truth_100k_mps_low_streamed/branch_site_neural_checkpoint.pt package/models/low_branch_site_neural_checkpoint.pt
