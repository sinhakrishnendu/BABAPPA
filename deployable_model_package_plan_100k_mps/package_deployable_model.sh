cp branch_site_calibration_explicit_branch_truth_100k_mps_low_streamed/branch_site_calibrated_metrics.json package/calibration/low_branch_site_calibrated_metrics.json
cp branch_site_neural_explicit_branch_truth_100k_mps_moderate_streamed/branch_site_neural_checkpoint.pt package/models/moderate_branch_site_neural_checkpoint.pt
cp branch_site_neural_explicit_branch_truth_100k_mps_moderate_streamed/branch_site_neural_model_meta.json package/models/moderate_branch_site_neural_model_meta.json
cp branch_site_calibration_explicit_branch_truth_100k_mps_moderate_streamed/branch_site_calibration.json package/calibration/moderate_branch_site_calibration.json
cp branch_site_calibration_explicit_branch_truth_100k_mps_moderate_streamed/branch_site_calibrated_metrics.json package/calibration/moderate_branch_site_calibrated_metrics.json
cp branch_site_neural_explicit_branch_truth_100k_mps_high_streamed/branch_site_neural_checkpoint.pt package/models/high_branch_site_neural_checkpoint.pt
