#!/usr/bin/env python3
"""Build codon MSA/tree benchmark inputs from Drosophila OrthoFinder results.

OrthoFinder provides protein MSAs and resolved gene trees. BABAPPA and HyPhy
aBSREL need codon alignments and matching tree labels. This script performs a
PAL2NAL-style conversion from OrthoFinder protein MSA columns back to codon MSA
columns using the curated CDS generated by drosophila_00_prepare_orthofinder_inputs.py.
"""

from __future__ import annotations

import argparse
import csv
import json
import re
from dataclasses import dataclass
from pathlib import Path


STOP_CODONS = {"TAA", "TAG", "TGA"}


@dataclass
class FastaRecord:
    header: str
    seq: str


def parse_fasta(path: Path) -> list[FastaRecord]:
    records: list[FastaRecord] = []
    header = None
    chunks: list[str] = []
    with path.open() as handle:
        for raw in handle:
            line = raw.strip()
            if not line:
                continue
            if line.startswith(">"):
                if header is not None:
                    records.append(FastaRecord(header, "".join(chunks)))
                header = line[1:].split()[0]
                chunks = []
            else:
                chunks.append(line)
    if header is not None:
        records.append(FastaRecord(header, "".join(chunks)))
    return records


def write_fasta(records: list[tuple[str, str]], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w") as handle:
        for header, seq in records:
            handle.write(f">{header}\n")
            for idx in range(0, len(seq), 80):
                handle.write(seq[idx : idx + 80] + "\n")


def latest_results_dir(root: Path) -> Path:
    if (root / "Orthogroups").exists():
        return root
    candidates = sorted(root.glob("**/Results_*"), key=lambda p: p.stat().st_mtime, reverse=True)
    if not candidates:
        raise FileNotFoundError(f"No OrthoFinder Results_* directory found under {root}")
    return candidates[0]


def load_cds_records(prepared_dir: Path) -> dict[str, str]:
    records: dict[str, str] = {}
    for path in sorted((prepared_dir / "curated_cds").glob("*.cds.fasta")):
        for record in parse_fasta(path):
            records[record.header] = re.sub(r"\s+", "", record.seq.upper().replace("U", "T")).replace("-", "")
    return records


def load_species_names(prepared_dir: Path) -> list[str]:
    names = [path.name.replace(".cds.fasta", "") for path in (prepared_dir / "curated_cds").glob("*.cds.fasta")]
    return sorted(names, key=len, reverse=True)


def load_single_copy(results: Path) -> list[str]:
    path = results / "Orthogroups" / "Orthogroups_SingleCopyOrthologues.txt"
    if not path.exists():
        raise FileNotFoundError(f"Missing single-copy orthologue file: {path}")
    return [line.strip() for line in path.read_text().splitlines() if line.strip()]


def load_tree_index(results: Path) -> dict[str, str]:
    path = results / "Resolved_Gene_Trees" / "Resolved_Gene_Trees.txt"
    if not path.exists():
        raise FileNotFoundError(f"Missing resolved gene tree index: {path}")
    trees: dict[str, str] = {}
    with path.open() as handle:
        for raw in handle:
            line = raw.strip()
            if not line or ":" not in line:
                continue
            og, tree = line.split(":", 1)
            tree = tree.strip()
            if tree:
                trees[og.strip()] = tree
    return trees


def resolve_cds_id(protein_msa_header: str, cds_records: dict[str, str], species_names: list[str]) -> str | None:
    if protein_msa_header in cds_records:
        return protein_msa_header
    for species in species_names:
        prefix = f"{species}_"
        if protein_msa_header.startswith(prefix):
            candidate = protein_msa_header[len(prefix):]
            if candidate in cds_records:
                return candidate
    return None


def trimmed_cds_codons(cds: str) -> tuple[list[str], str]:
    if len(cds) % 3 != 0:
        return [], "length_not_divisible_by_3"
    codons = [cds[i : i + 3] for i in range(0, len(cds), 3)]
    if codons and codons[-1] in STOP_CODONS:
        codons = codons[:-1]
    if any(codon in STOP_CODONS for codon in codons):
        return [], "internal_stop"
    return codons, "ok"


def codon_align_from_protein_msa(
    protein_records: list[FastaRecord],
    cds_records: dict[str, str],
    species_names: list[str],
    require_start_codon: bool,
) -> tuple[list[tuple[str, str]], dict[str, int | str]]:
    aligned: list[tuple[str, str]] = []
    stats: dict[str, int | str] = {
        "status": "ok",
        "n_records": len(protein_records),
        "n_start_fail": 0,
        "n_cds_missing": 0,
        "n_cds_integrity_fail": 0,
        "n_residue_codon_mismatch": 0,
    }
    for record in protein_records:
        cds_id = resolve_cds_id(record.header, cds_records, species_names)
        if cds_id is None:
            stats["n_cds_missing"] = int(stats["n_cds_missing"]) + 1
            continue
        cds = cds_records[cds_id]
        if require_start_codon and cds[:3] != "ATG":
            stats["n_start_fail"] = int(stats["n_start_fail"]) + 1
            continue
        codons, reason = trimmed_cds_codons(cds)
        if reason != "ok":
            stats["n_cds_integrity_fail"] = int(stats["n_cds_integrity_fail"]) + 1
            continue

        codon_index = 0
        aligned_codons: list[str] = []
        for aa in record.seq:
            if aa == "-":
                aligned_codons.append("---")
            else:
                if codon_index >= len(codons):
                    stats["n_cds_integrity_fail"] = int(stats["n_cds_integrity_fail"]) + 1
                    break
                aligned_codons.append(codons[codon_index])
                codon_index += 1
        else:
            aligned.append((record.header, "".join(aligned_codons)))
            continue
        continue

    if len(aligned) != len(protein_records):
        stats["status"] = "fail"
    lengths = {len(seq) for _, seq in aligned}
    if len(lengths) != 1 or (lengths and next(iter(lengths)) % 3 != 0):
        stats["status"] = "fail"
    stats["alignment_nt_length"] = next(iter(lengths)) if len(lengths) == 1 else 0
    stats["n_codons"] = int(stats["alignment_nt_length"]) // 3 if stats["alignment_nt_length"] else 0
    return aligned, stats


def tree_tip_labels(tree: str) -> set[str]:
    labels = set()
    token = []
    for char in tree:
        if char in "(),:;":
            if token:
                label = "".join(token).strip()
                if label and not label.startswith("n") and not re.fullmatch(r"[0-9. Ee+-]+", label):
                    labels.add(label)
                token = []
        else:
            token.append(char)
    return labels


def gap_fraction(aligned: list[tuple[str, str]]) -> float:
    total = sum(len(seq) for _, seq in aligned)
    if total == 0:
        return 1.0
    gaps = sum(seq.count("-") for _, seq in aligned)
    return gaps / total


def mean_pairwise_p_distance(aligned: list[tuple[str, str]]) -> float:
    if len(aligned) < 2:
        return 0.0
    distances: list[float] = []
    valid = set("ACGT")
    for i in range(len(aligned)):
        seq_a = aligned[i][1].upper()
        for j in range(i + 1, len(aligned)):
            seq_b = aligned[j][1].upper()
            compared = 0
            diffs = 0
            for base_a, base_b in zip(seq_a, seq_b):
                if base_a in valid and base_b in valid:
                    compared += 1
                    if base_a != base_b:
                        diffs += 1
            if compared:
                distances.append(diffs / compared)
    return sum(distances) / len(distances) if distances else 1.0


def build(args: argparse.Namespace) -> int:
    prepared_dir = Path(args.prepared_dir)
    results = latest_results_dir(Path(args.orthofinder_root))
    outdir = Path(args.outdir)
    msa_dir = outdir / "msas"
    tree_dir = outdir / "trees"
    outdir.mkdir(parents=True, exist_ok=True)

    cds_records = load_cds_records(prepared_dir)
    species_names = load_species_names(prepared_dir)
    single_copy = load_single_copy(results)
    trees = load_tree_index(results)

    summary_rows: list[dict[str, str | int]] = []
    panel_rows: list[dict[str, str]] = []
    n_written = 0

    for orthogroup in single_copy:
        if args.max_families and n_written >= args.max_families:
            break
        protein_msa = results / "MultipleSequenceAlignments" / f"{orthogroup}.fa"
        tree = trees.get(orthogroup, "")
        if not protein_msa.exists() or not tree:
            summary_rows.append({"panel_id": orthogroup, "status": "missing_alignment_or_tree"})
            continue
        protein_records = parse_fasta(protein_msa)
        aligned, stats = codon_align_from_protein_msa(
            protein_records,
            cds_records,
            species_names,
            require_start_codon=not args.allow_missing_start_codon,
        )
        status = str(stats["status"])
        if status != "ok":
            summary_rows.append({"panel_id": orthogroup, **stats})
            continue
        n_taxa = len(aligned)
        if n_taxa < args.min_taxa:
            summary_rows.append({"panel_id": orthogroup, **stats, "n_taxa": n_taxa, "status": "filtered_too_few_taxa"})
            continue
        n_codons = int(stats["n_codons"])
        if n_codons < args.min_codons or (args.max_codons and n_codons > args.max_codons):
            summary_rows.append({"panel_id": orthogroup, **stats, "n_taxa": n_taxa, "status": "filtered_codon_count"})
            continue
        gaps = gap_fraction(aligned)
        p_distance = mean_pairwise_p_distance(aligned)
        stats["n_taxa"] = n_taxa
        stats["gap_fraction"] = f"{gaps:.6f}"
        stats["mean_pairwise_p_distance"] = f"{p_distance:.6f}"
        if args.min_gap_fraction is not None and gaps < args.min_gap_fraction:
            summary_rows.append({"panel_id": orthogroup, **stats, "status": "filtered_low_gap_fraction"})
            continue
        if args.max_gap_fraction is not None and gaps > args.max_gap_fraction:
            summary_rows.append({"panel_id": orthogroup, **stats, "status": "filtered_high_gap_fraction"})
            continue
        if args.min_mean_pdistance is not None and p_distance < args.min_mean_pdistance:
            summary_rows.append({"panel_id": orthogroup, **stats, "status": "filtered_low_p_distance"})
            continue
        if args.max_mean_pdistance is not None and p_distance > args.max_mean_pdistance:
            summary_rows.append({"panel_id": orthogroup, **stats, "status": "filtered_high_p_distance"})
            continue
        msa_tips = {header for header, _ in aligned}
        tips = tree_tip_labels(tree)
        if tips and not tips.issubset(msa_tips):
            summary_rows.append({"panel_id": orthogroup, **stats, "status": "tree_msa_tip_mismatch"})
            continue

        msa_path = msa_dir / f"{orthogroup}.codon.aln.fasta"
        tree_path = tree_dir / f"{orthogroup}.treefile"
        write_fasta(aligned, msa_path)
        tree_path.parent.mkdir(parents=True, exist_ok=True)
        tree_path.write_text(tree if tree.endswith(";") else f"{tree};", encoding="utf-8")
        n_written += 1

        summary_rows.append({"panel_id": orthogroup, **stats, "status": "ok", "msa": str(msa_path), "tree": str(tree_path)})
        panel_rows.append({
            "panel_id": orthogroup,
            "gene_family": orthogroup,
            "cds_msa": str(msa_path),
            "tree_file": str(tree_path),
            "foreground": args.foreground,
            "expected_category": "unknown",
            "notes": "Drosophila OrthoFinder single-copy ortholog benchmark; BABAPPA and HyPhy aBSREL are both run on leaf branches.",
        })

    with (outdir / "drosophila_babappa_absrel_panel.tsv").open("w", newline="") as handle:
        writer = csv.DictWriter(
            handle,
            fieldnames=["panel_id", "gene_family", "cds_msa", "tree_file", "foreground", "expected_category", "notes"],
            delimiter="\t",
        )
        writer.writeheader()
        writer.writerows(panel_rows)

    fieldnames = sorted({key for row in summary_rows for key in row})
    with (outdir / "input_build_summary.tsv").open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames, delimiter="\t", extrasaction="ignore")
        writer.writeheader()
        writer.writerows(summary_rows)

    payload = {
        "status": "ok",
        "orthofinder_results": str(results),
        "families_written": n_written,
        "panel": str(outdir / "drosophila_babappa_absrel_panel.tsv"),
        "foreground": args.foreground,
        "require_start_codon": not args.allow_missing_start_codon,
        "min_taxa": args.min_taxa,
        "min_codons": args.min_codons,
        "max_codons": args.max_codons,
        "min_gap_fraction": args.min_gap_fraction,
        "max_gap_fraction": args.max_gap_fraction,
        "min_mean_pdistance": args.min_mean_pdistance,
        "max_mean_pdistance": args.max_mean_pdistance,
    }
    (outdir / "input_build_summary.json").write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    (outdir / "input_build_summary.md").write_text(
        "# Drosophila BABAPPA/aBSREL Benchmark Input Build\n\n"
        f"- OrthoFinder results: `{results}`\n"
        f"- families written: `{n_written}`\n"
        f"- panel: `{outdir / 'drosophila_babappa_absrel_panel.tsv'}`\n"
        f"- foreground mode for BABAPPA: `{args.foreground}`\n"
        f"- minimum taxa: `{args.min_taxa}`\n"
        f"- minimum codons: `{args.min_codons}`\n"
        f"- minimum gap fraction: `{args.min_gap_fraction}`\n"
        f"- maximum gap fraction: `{args.max_gap_fraction}`\n"
        f"- minimum mean p-distance: `{args.min_mean_pdistance}`\n"
        f"- maximum mean p-distance: `{args.max_mean_pdistance}`\n"
        "- HyPhy aBSREL benchmark scripts test leaf branches with `--branches leaves` by default.\n",
        encoding="utf-8",
    )
    print(f"Wrote {n_written} BABAPPA/aBSREL benchmark input families")
    print(outdir / "drosophila_babappa_absrel_panel.tsv")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--orthofinder-root", default="publication_benchmark/drosophila_orthofinder")
    parser.add_argument("--prepared-dir", default="publication_benchmark/drosophila_orthofinder")
    parser.add_argument("--outdir", default="publication_benchmark/drosophila_absrel_benchmark")
    parser.add_argument("--max-families", type=int, default=50, help="Use 0 for all single-copy orthologs.")
    parser.add_argument("--min-taxa", type=int, default=6)
    parser.add_argument("--min-codons", type=int, default=100)
    parser.add_argument("--max-codons", type=int, default=1500, help="Use 0 for no upper limit.")
    parser.add_argument("--min-gap-fraction", type=float, default=-1, help="Use -1 to disable.")
    parser.add_argument("--max-gap-fraction", type=float, default=0.25, help="Use -1 to disable.")
    parser.add_argument("--min-mean-pdistance", type=float, default=-1, help="Use -1 to disable.")
    parser.add_argument("--max-mean-pdistance", type=float, default=0.25, help="Use -1 to disable.")
    parser.add_argument("--foreground", default="leaves")
    parser.add_argument("--allow-missing-start-codon", action="store_true")
    args = parser.parse_args()
    if args.min_gap_fraction is not None and args.min_gap_fraction < 0:
        args.min_gap_fraction = None
    if args.max_gap_fraction is not None and args.max_gap_fraction < 0:
        args.max_gap_fraction = None
    if args.min_mean_pdistance is not None and args.min_mean_pdistance < 0:
        args.min_mean_pdistance = None
    if args.max_mean_pdistance is not None and args.max_mean_pdistance < 0:
        args.max_mean_pdistance = None
    return build(args)


if __name__ == "__main__":
    raise SystemExit(main())
